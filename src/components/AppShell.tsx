import { Link, useRouterState } from "@tanstack/react-router";
import type { ReactNode } from "react";
import {
  LayoutDashboard,
  Mail,
  NotebookPen,
  ListChecks,
  Search,
  MessagesSquare,
  Compass,
} from "lucide-react";
import {
  Sidebar,
  SidebarContent,
  SidebarFooter,
  SidebarGroup,
  SidebarGroupContent,
  SidebarGroupLabel,
  SidebarHeader,
  SidebarMenu,
  SidebarMenuButton,
  SidebarMenuItem,
  SidebarProvider,
  SidebarTrigger,
} from "@/components/ui/sidebar";

export const tools = [
  { title: "Smart Email Generator", short: "Emails", url: "/email", icon: Mail, desc: "Draft polished emails from a few notes." },
  { title: "Meeting Notes Summarizer", short: "Meetings", url: "/meetings", icon: NotebookPen, desc: "Turn raw notes into decisions and action items." },
  { title: "AI Task Planner", short: "Planner", url: "/planner", icon: ListChecks, desc: "Break goals into a prioritised, scheduled plan." },
  { title: "AI Research Assistant", short: "Research", url: "/research", icon: Search, desc: "Structured briefings on any topic." },
  { title: "AI Chatbot", short: "Chat", url: "/chat", icon: MessagesSquare, desc: "Ask anything about your work." },
] as const;

function AppSidebar() {
  const path = useRouterState({ select: (r) => r.location.pathname });
  const items = [{ title: "Dashboard", url: "/", icon: LayoutDashboard }, ...tools];
  return (
    <Sidebar collapsible="icon">
      <SidebarHeader>
        <Link to="/" className="flex items-center gap-2 px-1 py-2">
          <span className="grid size-8 shrink-0 place-items-center rounded-lg bg-sidebar-primary text-sidebar-primary-foreground">
            <Compass className="size-4" />
          </span>
          <span className="font-display text-base font-semibold leading-tight group-data-[collapsible=icon]:hidden">
            Task Planner
            <span className="block text-xs font-normal text-sidebar-foreground/60">Productivity Assistant</span>
          </span>
        </Link>
      </SidebarHeader>
      <SidebarContent>
        <SidebarGroup>
          <SidebarGroupLabel>Workspace</SidebarGroupLabel>
          <SidebarGroupContent>
            <SidebarMenu>
              {items.map((i) => (
                <SidebarMenuItem key={i.url}>
                  <SidebarMenuButton asChild isActive={path === i.url} tooltip={i.title}>
                    <Link to={i.url}>
                      <i.icon />
                      <span>{"short" in i ? i.short : i.title}</span>
                    </Link>
                  </SidebarMenuButton>
                </SidebarMenuItem>
              ))}
            </SidebarMenu>
          </SidebarGroupContent>
        </SidebarGroup>
      </SidebarContent>
      <SidebarFooter className="text-xs text-sidebar-foreground/60 group-data-[collapsible=icon]:hidden">
        AI can make mistakes. Review before you send.
      </SidebarFooter>
    </Sidebar>
  );
}

export function AppShell({ children }: { children: ReactNode }) {
  return (
    <SidebarProvider>
      <div className="flex min-h-screen w-full">
        <AppSidebar />
        <div className="flex min-w-0 flex-1 flex-col">
          <header className="sticky top-0 z-10 flex h-14 items-center gap-2 border-b bg-background/80 px-3 backdrop-blur">
            <SidebarTrigger />
            <span className="text-sm text-muted-foreground">AI Task Planner · Productivity Assistant</span>
          </header>
          <main className="flex-1 px-4 py-6 md:px-8 md:py-8">{children}</main>
        </div>
      </div>
    </SidebarProvider>
  );
}

export function Disclaimer() {
  return (
    <div className="rounded-lg border border-accent/40 bg-accent/10 p-3 text-xs leading-relaxed text-foreground/80">
      <strong className="font-semibold">Responsible AI:</strong> outputs are generated by AI and may be
      inaccurate, incomplete or biased. Verify facts, check tone, and avoid sharing confidential or
      personal data. You remain responsible for anything you send or act on.
    </div>
  );
}
